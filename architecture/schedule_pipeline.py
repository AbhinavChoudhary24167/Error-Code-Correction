def _regime_sweep(
    *,
    payload: Mapping[str, object],
    modes: Mapping[str, ECCOperatingMode],
    designs: Sequence[ArchitectureDesign],
    transition_model: TransitionModel,
    policy: Mapping[str, object],
) -> dict:
    accesses_values = [int(value) for value in dict(payload.get("sweeps", {})).get("epoch_accesses", [1_000_000, 10_000_000, 100_000_000])]
    transition_multipliers = [float(value) for value in dict(payload.get("sweeps", {})).get("transition_energy_multipliers", [0.0, 1.0, 2.0])]
    matrix = []
    for accesses in accesses_values:
        row = []
        trace = generate_synthetic_trace({
            "family": "one_time_sbu_to_mbu", "seed": 1900, "epoch_count": 12,
            "accesses_per_epoch": accesses,
        })
        fixed_results = []
        for design in designs:
            if design.architecture_mode == "fixed":
                results, _ = _run_design(trace=trace, modes=modes, design=design, transition_model=transition_model, policy=policy)
                fixed_results.append((design.design_id, results["best_static"]))
        best_fixed = _best_result(fixed_results)
        for multiplier in transition_multipliers:
            adaptive_results = []
            for design in designs:
                if design.architecture_mode != "adaptive":
                    continue
                results, costs = _run_design(trace=trace, modes=modes, design=design, transition_model=transition_model, policy=policy)
                nominal = results["transition_aware_dp"]
                if nominal.status != "ok":
                    continue
                # Re-optimize with a multiplicative transition sensitivity; no
                # PPA value is inferred from the multiplier.
                base_lookup = _transition_lookup(transition_model, design, trace)

                def scaled_lookup(index: int, old: str, new: str) -> TransitionCost:
                    item = base_lookup(index, old, new)
                    return replace(
                        item,
                        energy_j=(item.energy_j * multiplier if item.energy_j is not None else None),
                        carbon_kgco2e=(item.carbon_kgco2e * multiplier if item.carbon_kgco2e is not None else None),
                    )

                result = exact_dynamic_programming(
                    epoch_costs=costs, transition_lookup=scaled_lookup, design=design,
                    objective=str(policy["objective"]), min_dwell_epochs=int(policy["minimum_dwell_epochs"]),
                    max_transitions=_policy_max_transitions(policy, len(trace.epochs)),
                )
                adaptive_results.append((design.design_id, result))
            best_adaptive = _best_result(adaptive_results)
            row.append(
                int(
                    bool(best_fixed and best_adaptive)
                    and float(best_adaptive[1].total_objective) < float(best_fixed[1].total_objective)
                )
            )
        matrix.append(row)
    return {
        "trace_family": "one_time_sbu_to_mbu",
        "model_status": "normalized synthetic sensitivity",
        "epoch_accesses": accesses_values,
        "transition_energy_multipliers": transition_multipliers,
        "adaptive_beneficial": matrix,
    }


