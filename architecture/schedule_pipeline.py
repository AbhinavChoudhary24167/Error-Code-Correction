def _write_json(path: Path, payload: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, sort_keys=True, allow_nan=False) + "\n", encoding="utf-8")


def _write_csv(path: Path, rows: Sequence[Mapping[str, object]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        path.write_text("", encoding="utf-8")
        return
    fields = list(rows[0])
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)


def _write_schedule_package(
    path: Path,
    *,
    modes: Sequence[str],
    schedule: Sequence[str],
    safe_fallback: str,
    minimum_dwell_epochs: int,
) -> None:
    if safe_fallback not in modes:
        raise ValueError("safe fallback must be present in schedule mode table")
    width = max(1, math.ceil(math.log2(len(modes))))
    indices = [modes.index(mode) for mode in schedule]
    lines = [
        "// Generated by GREEN-ECC transition-aware scheduling. Do not edit manually.",
        "// This is a policy package; it does not implement the migration datapath.",
        "package green_ecc_schedule_pkg;",
        f"  localparam int ECC_MODE_COUNT = {len(modes)};",
        f"  localparam int ECC_MODE_WIDTH = {width};",
        f"  localparam int ECC_SCHEDULE_EPOCHS = {len(schedule)};",
        f"  localparam int ECC_MIN_DWELL_EPOCHS = {minimum_dwell_epochs};",
        f"  localparam logic [ECC_MODE_WIDTH-1:0] ECC_SAFE_FALLBACK = ECC_MODE_WIDTH'({modes.index(safe_fallback)});",
        "  localparam logic [ECC_MODE_WIDTH-1:0] ECC_EPOCH_MODE [0:ECC_SCHEDULE_EPOCHS-1] = '{",
        "    " + ", ".join(f"ECC_MODE_WIDTH'({index})" for index in indices),
        "  };",
    ]
    for index, mode in enumerate(modes):
        token = "".join(character if character.isalnum() else "_" for character in mode.upper())
        lines.append(f"  localparam logic [ECC_MODE_WIDTH-1:0] ECC_MODE_{token} = ECC_MODE_WIDTH'({index});")
    lines.extend(["endpackage", ""])
    path.write_text("\n".join(lines), encoding="utf-8")


