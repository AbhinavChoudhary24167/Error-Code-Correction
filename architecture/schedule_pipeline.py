def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _repository_state(repo_root: Path) -> tuple[str | None, bool]:
    try:
        commit = subprocess.run(
            ["git", "rev-parse", "HEAD"], cwd=repo_root, check=True,
            capture_output=True, text=True, timeout=10,
        ).stdout.strip()
        dirty = bool(
            subprocess.run(
                ["git", "status", "--porcelain"], cwd=repo_root, check=True,
                capture_output=True, text=True, timeout=10,
            ).stdout.strip()
        )
        return commit, dirty
    except (OSError, subprocess.SubprocessError):
        return None, True


def _validate_input(payload: Mapping[str, object], repo_root: Path) -> None:
    required = {
        "schema_version", "study_id", "model_status", "modes", "designs",
        "transition_costs", "policy", "trace_generators", "uncertainty_samples",
    }
    missing = sorted(required - set(payload))
    if missing:
        raise ValueError(f"transition scheduling config missing: {', '.join(missing)}")
    if int(payload["schema_version"]) != 1:
        raise ValueError("unsupported transition scheduling schema version")
    composite_schema = json.loads(
        (repo_root / "schemas" / "transition-schedule-config.schema.json").read_text(
            encoding="utf-8"
        )
    )
    jsonschema.validate(payload, composite_schema)
    for key, schema_name in (
        ("transition_costs", "transition-cost-matrix.schema.json"),
        ("policy", "scheduling-policy.schema.json"),
    ):
        schema = json.loads((repo_root / "schemas" / schema_name).read_text(encoding="utf-8"))
        jsonschema.validate(payload[key], schema)


def _transition_lookup(
    model: TransitionModel, design: ArchitectureDesign, trace: ScenarioTrace
):
    def lookup(index: int, old: str, new: str) -> TransitionCost:
        return model.evaluate(from_ecc=old, to_ecc=new, design=design, epoch=trace.epochs[index])

    return lookup


def _policy_max_transitions(policy: Mapping[str, object], epoch_count: int) -> int | None:
    limits = []
    if policy.get("maximum_transitions") is not None:
        limits.append(int(policy["maximum_transitions"]))
    if policy.get("maximum_switch_rate_per_epoch") is not None:
        limits.append(math.floor(float(policy["maximum_switch_rate_per_epoch"]) * epoch_count))
    return min(limits) if limits else None


def _apply_certificate_gate(
    *,
    trace: ScenarioTrace,
    costs: Sequence[Mapping[str, EpochModeCost]],
    gate: Mapping[str, object] | None,
    envelopes: Sequence[Mapping[str, object]],
) -> tuple[dict[str, EpochModeCost], ...]:
    """Make out-of-envelope modes infeasible before any scheduling policy runs."""

    if not gate or not bool(gate.get("enabled", False)):
        return tuple(dict(row) for row in costs)
    by_mode = {str(item["mode_id"]): item for item in envelopes}
    radius_key = str(gate.get("epoch_radius_uncertainty_key", "ambiguity_radius"))
    required_type = str(gate["ambiguity_type"])
    maximum_sdc = float(gate["maximum_sdc"])
    support_by_regime = {
        str(key): str(value)
        for key, value in dict(gate.get("support_id_by_fault_regime", {})).items()
    }
    output = []
    for epoch, row in zip(trace.epochs, costs):
        observed_radius = epoch.uncertainty.get(radius_key)
        gated_row = {}
        for mode, item in row.items():
            envelope = by_mode.get(mode)
            reasons = []
            if envelope is None:
                reasons.append("certificate_gate:mode_not_registered")
            else:
                current_support = support_by_regime.get(epoch.fault_regime)
                if current_support is None:
                    reasons.append("certificate_gate:current_support_identifier_missing")
                elif current_support != str(envelope.get("support_identifier", "")):
                    reasons.append("certificate_gate:error_support_not_contained")
                if str(envelope["ambiguity_type"]) != required_type:
                    reasons.append("certificate_gate:ambiguity_type_mismatch")
                if observed_radius is None:
                    reasons.append("certificate_gate:epoch_confidence_radius_missing")
                elif float(observed_radius) > float(envelope["certified_radius"]) + 1e-15:
                    reasons.append("certificate_gate:confidence_region_outside_envelope")
                if float(envelope["maximum_certified_sdc"]) > maximum_sdc + 1e-15:
                    reasons.append("certificate_gate:sdc_limit_exceeded")
                if epoch.fault_regime not in set(envelope.get("supported_fault_regimes", [])):
                    reasons.append("certificate_gate:fault_regime_not_supported")
                if not str(envelope.get("certificate_identifier", "")):
                    reasons.append("certificate_gate:certificate_identifier_missing")
            if reasons:
                gated_row[mode] = replace(
                    item,
                    feasible=False,
                    feasibility_probability=0.0,
                    violations=tuple(item.violations) + tuple(reasons),
                )
            else:
                gated_row[mode] = item
        output.append(gated_row)
    return tuple(output)


def _run_design(
    *,
    trace: ScenarioTrace,
    modes: Mapping[str, ECCOperatingMode],
    design: ArchitectureDesign,
    transition_model: TransitionModel,
    policy: Mapping[str, object],
    certificate_gate: Mapping[str, object] | None = None,
    certificate_envelopes: Sequence[Mapping[str, object]] = (),
) -> tuple[dict[str, ScheduleResult], tuple[dict[str, EpochModeCost], ...]]:
    objective = str(policy["objective"])
    maximum_transitions = _policy_max_transitions(policy, len(trace.epochs))
    costs = build_epoch_costs(
        trace,
        modes,
        design,
        objective=objective,
        area_limit_mm2=(
            float(policy["area_limit_mm2"])
            if policy.get("area_limit_mm2") is not None
            else None
        ),
    )
    costs = _apply_certificate_gate(
        trace=trace,
        costs=costs,
        gate=certificate_gate,
        envelopes=certificate_envelopes,
    )
    lookup = _transition_lookup(transition_model, design, trace)
    static = best_static_schedule(
        epoch_costs=costs,
        transition_lookup=lookup,
        design=design,
        objective=objective,
    )
    results: dict[str, ScheduleResult] = {"best_static": static}
    if design.architecture_mode != "adaptive":
        return results, costs
    results["snapshot_oracle"] = snapshot_oracle_schedule(
        epoch_costs=costs,
        transition_lookup=lookup,
        design=design,
        objective=objective,
    )
    results["greedy"] = greedy_schedule(
        epoch_costs=costs,
        transition_lookup=lookup,
        design=design,
        objective=objective,
    )
    results["fault_regime_lookup"] = fault_lookup_schedule(
        trace=trace,
        lookup=dict(policy["fault_regime_lookup"]),
        epoch_costs=costs,
        transition_lookup=lookup,
        design=design,
        objective=objective,
        safe_fallback=str(policy["safe_fallback_ecc"]),
    )
    results["transition_aware_dp"] = exact_dynamic_programming(
        epoch_costs=costs,
        transition_lookup=lookup,
        design=design,
        objective=objective,
        min_dwell_epochs=int(policy["minimum_dwell_epochs"]),
        max_transitions=maximum_transitions,
    )
    results["robust_transition_aware"] = robust_dynamic_programming(
        epoch_costs=costs,
        transition_lookup=lookup,
        design=design,
        objective=objective,
        chance_constraint_epsilon=float(policy["chance_constraint_epsilon"]),
        risk_aversion_z=float(policy["risk_aversion_z"]),
        min_dwell_epochs=int(policy["minimum_dwell_epochs"]),
        max_transitions=maximum_transitions,
    )
    results["robust_hysteresis"] = hysteresis_schedule(
        epoch_costs=costs,
        transition_lookup=lookup,
        design=design,
        objective=objective,
        prediction_horizon_epochs=int(policy["prediction_horizon_epochs"]),
        min_dwell_epochs=int(policy["minimum_dwell_epochs"]),
        minimum_benefit_margin=float(policy["minimum_benefit_margin"]),
        max_transitions=maximum_transitions,
        confidence_threshold=float(policy["confidence_threshold"]),
        uncertainty_z=float(policy["risk_aversion_z"]),
        safe_fallback=str(policy["safe_fallback_ecc"]),
    )
    return results, costs


def _best_result(items: Sequence[tuple[str, ScheduleResult]]) -> tuple[str, ScheduleResult] | None:
    feasible = [(name, item) for name, item in items if item.status == "ok" and item.total_objective is not None]
    return min(feasible, key=lambda value: (float(value[1].total_objective), value[0])) if feasible else None


def _transition_break_even(
    *,
    result: ScheduleResult,
    costs: Sequence[Mapping[str, EpochModeCost]],
    lookup,
    objective: str,
) -> list[dict]:
    output = []
    for index in range(1, len(result.path)):
        old = result.path[index - 1]
        new = result.path[index]
        if old == new:
            continue
        old_cost = costs[index][old]
        new_cost = costs[index][new]
        transition = lookup(index, old, new)
        if objective == "lifecycle_energy_j":
            old_per_access = (
                float(old_cost.operational_energy_j) / max(1, int(old_cost.cost_breakdown.get("accesses", 0) or 1))
                if old_cost.operational_energy_j is not None
                else None
            )
            new_per_access = (
                float(new_cost.operational_energy_j) / max(1, int(new_cost.cost_breakdown.get("accesses", 0) or 1))
                if new_cost.operational_energy_j is not None
                else None
            )
        else:
            accesses = max(1, int(old_cost.cost_breakdown.get("accesses", 0) or 1))
            old_per_access = (
                float(old_cost.operational_carbon_kgco2e) / accesses
                if old_cost.operational_carbon_kgco2e is not None
                else None
            )
            new_per_access = (
                float(new_cost.operational_carbon_kgco2e) / accesses
                if new_cost.operational_carbon_kgco2e is not None
                else None
            )
        # Within an already-instantiated adaptive design, continuing MUX/control
        # overhead is common to both states and cancels. Architecture adoption
        # overhead is handled separately in the fixed-vs-adaptive comparison.
        one_time = transition.objective_cost(objective)
        break_even = break_even_horizon(
            current_cost_per_access=old_per_access,
            new_cost_per_access=new_per_access,
            continuing_adaptive_overhead_per_access=0.0,
            one_time_transition_cost=one_time,
            feasible=transition.allowed,
            units=("J and J/access" if objective == "lifecycle_energy_j" else "kgCO2e and kgCO2e/access"),
        )
        output.append(
            {
                "epoch_index": index,
                "from_ecc": old,
                "to_ecc": new,
                "transition": transition.to_dict(),
                "break_even": break_even.to_dict(),
            }
        )
    return output


def _continuing_adaptability_overhead(
    result: ScheduleResult,
    costs: Sequence[Mapping[str, EpochModeCost]],
    objective: str,
) -> float | None:
    field = (
        "continuing_adaptability_energy_j"
        if objective == "lifecycle_energy_j"
        else "continuing_adaptability_carbon_kgco2e"
    )
    total = 0.0
    for index, mode in enumerate(result.path):
        value = costs[index][mode].cost_breakdown.get(field)
        if value is None:
            return None
        total += float(value)
    return total


def _uncertainty_study(
    *,
    nominal_costs: Sequence[Mapping[str, EpochModeCost]],
    transition_lookup,
    design: ArchitectureDesign,
    objective: str,
    samples: int,
    seed: int,
    min_dwell: int,
    max_transitions: int | None,
    reference: ScheduleResult,
) -> dict:
    rng = random.Random(seed)
    paths = []
    reference_regrets = []
    reference_feasible = 0
    beneficial = 0
    for _ in range(samples):
        sampled = []
        for costs in nominal_costs:
            row = {}
            for mode, cost in costs.items():
                relative = cost.objective_std * math.sqrt(3.0) / abs(float(cost.objective_cost or 1.0))
                factor = rng.uniform(max(0.0, 1.0 - relative), 1.0 + relative)
                row[mode] = replace(
                    cost,
                    objective_cost=(
                        float(cost.objective_cost) * factor if cost.objective_cost is not None else None
                    ),
                    feasible=(cost.feasible and rng.random() <= cost.feasibility_probability),
                )
            sampled.append(row)
        optimum = exact_dynamic_programming(
            epoch_costs=sampled,
            transition_lookup=transition_lookup,
            design=design,
            objective=objective,
            min_dwell_epochs=min_dwell,
            max_transitions=max_transitions,
            policy_name="uncertainty_sample_optimum",
        )
        static = best_static_schedule(
            epoch_costs=sampled,
            transition_lookup=transition_lookup,
            design=design,
            objective=objective,
        )
        if optimum.status == "ok":
            paths.append(optimum.path)
            if static.status == "ok" and float(optimum.total_objective) < float(static.total_objective):
                beneficial += 1
        if reference.path:
            from .scheduling import evaluate_path

            evaluated = evaluate_path(
                policy_name="reference_under_sample",
                path=reference.path,
                epoch_costs=sampled,
                transition_lookup=transition_lookup,
                design=design,
                objective=objective,
                theoretical_complexity="fixed path evaluation",
            )
            if evaluated.status == "ok" and optimum.status == "ok":
                reference_feasible += 1
                reference_regrets.append(float(evaluated.total_objective) - float(optimum.total_objective))
    reference_regrets.sort()
    p95_index = max(0, math.ceil(0.95 * len(reference_regrets)) - 1) if reference_regrets else 0
    stability = schedule_stability(paths)
    return {
        "samples": samples,
        "seed": seed,
        "distribution": "independent uniform objective intervals plus Bernoulli chance-feasibility draws",
        "probability_reference_schedule_feasible": reference_feasible / samples,
        "probability_switching_beneficial_vs_same_design_static": beneficial / samples,
        "reference_regret_mean": (
            sum(reference_regrets) / len(reference_regrets) if reference_regrets else None
        ),
        "reference_regret_p95": reference_regrets[p95_index] if reference_regrets else None,
        "schedule_stability": stability,
    }


def _dummy_scalability_benchmark() -> list[dict]:
    rows = []
    for epochs in (8, 32, 128):
        for mode_count in (2, 4, 8, 16):
            names = tuple(f"m{index}" for index in range(mode_count))
