// Exact shortened primitive BCH(78,64,t=2) implementation for Gate 03R.
// This file is independent of the repository's rejected degree-12 cyclic RTL.

module bch_78_64_t2_v1_encoder (
  input  logic [63:0] data_i,
  output logic [77:0] codeword_o
);
  localparam logic [14:0] G_POLY = 15'b101010001111101;
  logic [77:0] work;
  integer dividend_index, coefficient_index;

  // The encoder depends only on data_i; the explicit sensitivity list also
  // prevents loop-temporary re-entry in conservative event simulators.
  always @(data_i) begin
    work = '0;
    work[77:14] = data_i;
    for (dividend_index = 77; dividend_index >= 14; dividend_index = dividend_index - 1) begin
      if (work[dividend_index]) begin
        for (coefficient_index = 0; coefficient_index <= 14; coefficient_index = coefficient_index + 1)
          work[dividend_index-coefficient_index] =
            work[dividend_index-coefficient_index] ^ G_POLY[14-coefficient_index];
      end
    end
    codeword_o = {work[13:0], data_i};
  end
endmodule

