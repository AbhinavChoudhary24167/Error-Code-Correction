  function automatic logic [6:0] gf_mul(input logic [6:0] left, input logic [6:0] right);
    logic [7:0] a;
    logic [6:0] b;
    logic [6:0] result;
    integer bit_index;
    begin
      a = {1'b0, left};
      b = right;
      result = '0;
      for (bit_index = 0; bit_index < 7; bit_index = bit_index + 1) begin
        if (b[0]) result = result ^ a[6:0];
        b = b >> 1;
        a = a << 1;
        if (a[7]) a = a ^ 8'h83;
      end
      gf_mul = result;
    end
  endfunction

  function automatic logic [6:0] gf_inverse(input logic [6:0] value);
    logic [6:0] result, base;
    integer bit_index;
    begin
      result = 7'd1;
      base = value;
      for (bit_index = 0; bit_index < 7; bit_index = bit_index + 1) begin
        if ((126 >> bit_index) & 1) result = gf_mul(result, base);
        base = gf_mul(base, base);
      end
      gf_inverse = value == 0 ? 7'd0 : result;
    end
  endfunction

