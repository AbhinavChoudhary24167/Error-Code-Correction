  function automatic logic [27:0] calculate_syndrome(input logic [77:0] word);
    logic [27:0] packed_syndrome;
    integer coordinate;
    begin
      packed_syndrome = '0;
      for (coordinate = 0; coordinate < 78; coordinate = coordinate + 1)
        if (word[coordinate])
          packed_syndrome = packed_syndrome ^ coordinate_syndrome(coordinate);
      calculate_syndrome = packed_syndrome;
    end
  endfunction

  // The decoder depends only on its received word.  An explicit sensitivity
  // list avoids simulator-specific always_comb re-entry on loop temporaries.
  always @(codeword_i) begin
    received_syndrome = calculate_syndrome(codeword_i);
    syndrome_o = received_syndrome;
    s1 = received_syndrome[6:0];
    s3 = received_syndrome[20:14];
    s1_squared = gf_mul(s1, s1);
    s1_cubed = gf_mul(s1_squared, s1);
    sigma2 = gf_mul(s3 ^ s1_cubed, gf_inverse(s1));

    candidate_mask = '0;
    root_count = 0;
    position = 0;
    location_value = '0;
    locator_value = '0;
    if ((received_syndrome != '0) && (s1 != '0)) begin
      for (position = 0; position < 78; position = position + 1) begin
        location_value = location_element(position);
        locator_value = gf_mul(location_value, location_value)
          ^ gf_mul(s1, location_value) ^ sigma2;
        if (locator_value == 0) begin
          candidate_mask[position] = 1'b1;
          root_count = root_count + 1;
        end
      end
    end

    candidate_codeword = codeword_i ^ candidate_mask;
    corrected_syndrome = calculate_syndrome(candidate_codeword);

    correction_mask_o = '0;
    corrected_codeword_o = codeword_i;
    data_o = codeword_i[63:0];
    err_detected_o = received_syndrome != '0;
    err_corrected_o = 1'b0;
    err_uncorrectable_o = 1'b0;

    if (received_syndrome != '0) begin
      if ((s1 != '0) && ((root_count == 1) || (root_count == 2))
          && (corrected_syndrome == '0)) begin
        correction_mask_o = candidate_mask;
        corrected_codeword_o = candidate_codeword;
        data_o = candidate_codeword[63:0];
        err_corrected_o = 1'b1;
      end else begin
        err_uncorrectable_o = 1'b1;
      end
    end
